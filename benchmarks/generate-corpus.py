#!/usr/bin/env python3
"""Generate a deterministic mixed compression/restore benchmark corpus."""
from __future__ import annotations

import argparse
import gzip
import hashlib
import json
import os
import pathlib
import random
import shutil
import subprocess
import zipfile

FIXED_ZIP_TIME = (2020, 1, 1, 0, 0, 0)
FIXED_MTIME = 1_577_836_800


def zip_write(
    archive: zipfile.ZipFile,
    name: str,
    data,
    *,
    compression=None,
    level=None,
) -> None:
    info = zipfile.ZipInfo(name, FIXED_ZIP_TIME)
    info.compress_type = archive.compression if compression is None else compression
    info.external_attr = 0o100644 << 16
    info._compresslevel = level
    archive.writestr(info, data)


def write_to_size(path: pathlib.Path, block: bytes, size: int) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("wb") as handle:
        remaining = size
        while remaining:
            chunk = block[:remaining]
            handle.write(chunk)
            remaining -= len(chunk)


def deterministic_noise(size: int) -> bytes:
    output = bytearray()
    counter = 0
    while len(output) < size:
        output.extend(hashlib.sha256(f"hardcore-archive:{counter}".encode()).digest())
        counter += 1
    return bytes(output[:size])


def make_docx(path: pathlib.Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    document = "<w:document xmlns:w='http://schemas.openxmlformats.org/wordprocessingml/2006/main'><w:body>"
    document += "".join(f"<w:p><w:r><w:t>Compression paragraph {i:05d}</w:t></w:r></w:p>" for i in range(4000))
    document += "</w:body></w:document>"
    with zipfile.ZipFile(path, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=3) as archive:
        zip_write(archive, "[Content_Types].xml", "<Types xmlns='http://schemas.openxmlformats.org/package/2006/content-types'/>", level=3)
        zip_write(archive, "_rels/.rels", "<Relationships xmlns='http://schemas.openxmlformats.org/package/2006/relationships'/>", level=3)
        zip_write(archive, "word/document.xml", document, level=3)


def make_media(root: pathlib.Path) -> None:
    ffmpeg = shutil.which("ffmpeg")
    if not ffmpeg:
        raise SystemExit("--with-media requires ffmpeg")
    media = root / "media"
    media.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        [
            ffmpeg, "-hide_banner", "-loglevel", "error", "-y",
            "-f", "lavfi", "-i", "testsrc2=size=1920x1080:rate=30",
            "-f", "lavfi", "-i", "sine=frequency=1000:sample_rate=48000",
            "-t", "12", "-c:v", "libx264", "-crf", "16", "-preset", "medium",
            "-c:a", "flac", str(media / "reference-video.mkv"),
        ],
        check=True,
    )
    subprocess.run(
        [ffmpeg, "-hide_banner", "-loglevel", "error", "-y", "-f", "lavfi", "-i",
         "mandelbrot=size=2048x2048", "-frames:v", "1", str(media / "reference-image.png")],
        check=True,
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("output", nargs="?", default="benchmarks/corpus")
    parser.add_argument("--size-mib", type=int, default=64)
    parser.add_argument("--with-media", action="store_true")
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()
    if args.size_mib < 4:
        parser.error("--size-mib must be at least 4")

    root = pathlib.Path(args.output).resolve()
    if root.exists():
        if not args.force:
            raise SystemExit(f"corpus already exists: {root}; use --force")
        marker = root / ".hardcore-benchmark-corpus-v1"
        if not marker.is_file():
            raise SystemExit(
                f"refusing --force because this is not a marked benchmark corpus: {root}"
            )
        shutil.rmtree(root)
    root.mkdir(parents=True)
    (root / ".hardcore-benchmark-corpus-v1").write_text(
        "Generated by benchmarks/generate-corpus.py\n", encoding="utf-8"
    )

    total = args.size_mib * 1024 * 1024
    unit = max(256 * 1024, total // 8)
    text_block = (
        "Hardcore Archive deterministic benchmark data. "
        "This line contains repeated prose, punctuation, numbers 0123456789, and UTF-8 æøå.\n"
    ).encode() * 512
    write_to_size(root / "text" / "repeated.txt", text_block, unit * 2)

    records = root / "structured" / "events.jsonl"
    records.parent.mkdir(parents=True)
    with records.open("w", encoding="utf-8") as handle:
        index = 0
        while handle.tell() < unit:
            handle.write(json.dumps({"id": index, "group": index % 25, "status": "archived", "message": f"event-{index % 100}"}, separators=(",", ":")) + "\n")
            index += 1

    pattern = bytes(range(256)) * 4096
    write_to_size(root / "binary" / "pattern.bin", pattern, unit)
    write_to_size(root / "binary" / "incompressible.bin", deterministic_noise(unit), unit)

    small = root / "small-files"
    small.mkdir()
    for index in range(1000):
        (small / f"item-{index:04d}.txt").write_text(f"group={index % 20}\nvalue={index}\n" * 8, encoding="utf-8")

    duplicate = deterministic_noise(max(64 * 1024, unit // 8))
    for index in range(8):
        write_to_size(root / "duplicates" / f"copy-{index}.bin", duplicate, len(duplicate))

    sparse = root / "filesystem" / "sparse.bin"
    sparse.parent.mkdir(parents=True)
    with sparse.open("wb") as handle:
        handle.write(b"BEGIN")
        handle.seek(unit * 2)
        handle.write(b"END")

    source_text = (root / "text" / "repeated.txt").read_bytes()
    compressed = root / "already-compressed" / "repeated.txt.gz"
    compressed.parent.mkdir(parents=True)
    with gzip.GzipFile(filename=compressed, mode="wb", compresslevel=9, mtime=0) as handle:
        handle.write(source_text)

    nested = root / "nested" / "payload.zip"
    nested.parent.mkdir(parents=True)
    with zipfile.ZipFile(nested, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=4) as archive:
        zip_write(archive, "notes.txt", text_block, level=4)
        zip_write(archive, "pattern.bin", pattern, level=4)

    make_docx(root / "containers" / "benchmark.docx")
    if args.with_media:
        make_media(root)

    for path in sorted(root.rglob("*"), reverse=True):
        if path.is_symlink():
            continue
        path.chmod(0o755 if path.is_dir() else 0o644)
        os.utime(path, (FIXED_MTIME, FIXED_MTIME), follow_symlinks=False)
    root.chmod(0o755)
    os.utime(root, (FIXED_MTIME, FIXED_MTIME), follow_symlinks=False)

    manifest = root.parent / f"{root.name}.sha256"
    with manifest.open("w", encoding="utf-8") as handle:
        for path in sorted(p for p in root.rglob("*") if p.is_file()):
            digest = hashlib.sha256(path.read_bytes()).hexdigest()
            handle.write(f"{digest}  {path.relative_to(root)}\n")
    print(f"Corpus:   {root}")
    print(f"Manifest: {manifest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
